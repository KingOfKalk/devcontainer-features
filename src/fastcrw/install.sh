#!/usr/bin/env bash
# Installs the fastCRW CLI (https://github.com/fastcrw/crw).
# The real binary goes to /usr/local/lib/fastcrw, a wrapper on PATH applies
# the user agent option to every invocation.
set -euo pipefail

VERSION="${VERSION:-latest}"
USER_AGENT="${USERAGENT:-}"

REPO_URL="https://github.com/fastcrw/crw"
LIB_DIR="/usr/local/lib/fastcrw"
BIN="${LIB_DIR}/crw"
WRAPPER="/usr/local/bin/crw"

err() { echo "(!) fastcrw: $*" >&2; exit 1; }

ensure_deps() {
    if command -v curl >/dev/null 2>&1 && command -v tar >/dev/null 2>&1 && [ -e /etc/ssl/certs/ca-certificates.crt ]; then
        return
    fi
    command -v apt-get >/dev/null 2>&1 || err "curl, tar and ca-certificates are required and apt-get is not available"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y --no-install-recommends curl ca-certificates tar
    rm -rf /var/lib/apt/lists/*
}

detect_arch() {
    case "$(uname -m)" in
        x86_64 | amd64) echo "x64" ;;
        aarch64 | arm64) echo "arm64" ;;
        *) err "unsupported architecture: $(uname -m)" ;;
    esac
}

# Resolves 'latest' to a concrete tag once, so the tarball and SHA256SUMS
# always come from the same release.
release_url() {
    local tag
    if [ "${VERSION}" = "latest" ]; then
        # .../releases/latest/download/X redirects to .../releases/download/<tag>/X
        tag="$(curl -fsS -o /dev/null -w '%{redirect_url}' "${REPO_URL}/releases/latest/download/SHA256SUMS")" || err "could not resolve the latest release"
        tag="${tag%/SHA256SUMS}"
        tag="${tag##*/}"
        case "${tag}" in
            v[0-9]*) ;;
            *) err "could not resolve the latest release" ;;
        esac
    else
        tag="v${VERSION#v}"
    fi
    echo "${REPO_URL}/releases/download/${tag}"
}

# Verifies the tarball against the release's SHA256SUMS. Only a missing
# SHA256SUMS (old releases) produces a warning; any other error fails.
verify() {
    local dir="$1" asset="$2" url="$3" code
    code="$(curl -sL -o "${dir}/SHA256SUMS" -w '%{http_code}' "${url}/SHA256SUMS")" || err "download of SHA256SUMS failed"
    if [ "${code}" = "404" ]; then
        echo "(!) fastcrw: no SHA256SUMS for version '${VERSION}', skipping checksum verification" >&2
        return
    fi
    [ "${code}" = "200" ] || err "download of SHA256SUMS failed (HTTP ${code})"
    grep -q "  ${asset}\$" "${dir}/SHA256SUMS" || err "${asset} is missing from SHA256SUMS"
    (cd "${dir}" && sha256sum -c --ignore-missing --strict SHA256SUMS) || err "checksum mismatch for ${asset}"
}

# Single-quote a value for safe embedding in the generated script.
shell_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

write_wrapper() {
    {
        echo '#!/bin/sh'
        echo '# Generated by the fastcrw devcontainer feature.'
        echo "CRW_BIN=\"\${CRW_REAL_BIN:-${BIN}}\""
        echo "USER_AGENT=$(shell_quote "${USER_AGENT}")"
        cat <<'EOF'
if [ -n "$USER_AGENT" ] && [ -z "${CRW_CRAWLER__USER_AGENT+set}" ]; then
    export CRW_CRAWLER__USER_AGENT="$USER_AGENT"
fi
exec "$CRW_BIN" "$@"
EOF
    } > "${WRAPPER}"
    chmod 755 "${WRAPPER}"
}

if [ "$(id -u)" -ne 0 ]; then
    err "the install script must be run as root"
fi

ensure_deps
asset="crw-linux-$(detect_arch).tar.gz"
url="$(release_url)"
tmp="$(mktemp -d)"
curl -fsSL -o "${tmp}/${asset}" "${url}/${asset}" || err "download of ${asset} for version '${VERSION}' failed"
verify "${tmp}" "${asset}" "${url}"
tar -xzf "${tmp}/${asset}" -C "${tmp}" crw
mkdir -p "${LIB_DIR}"
install -m 755 "${tmp}/crw" "${BIN}"
rm -rf "${tmp}"
write_wrapper

echo "$("${BIN}" --version) installed"
