#!/usr/bin/env bash
# Installs Lightpanda (https://github.com/lightpanda-io/browser).
# The real binary goes to /usr/local/lib/lightpanda, a wrapper on PATH applies
# the telemetry and user agent options to every invocation.
# Upstream publishes no checksums; checksums.txt pins the sha256 of known
# releases and is checked when the installed version is listed there.
set -euo pipefail

VERSION="${VERSION:-latest}"
TELEMETRY="${TELEMETRY:-false}"
USER_AGENT="${USERAGENT:-}"

REPO_URL="https://github.com/lightpanda-io/browser"
CHECKSUMS="$(cd "$(dirname "$0")" && pwd)/checksums.txt"
LIB_DIR="/usr/local/lib/lightpanda"
BIN="${LIB_DIR}/lightpanda"
WRAPPER="/usr/local/bin/lightpanda"

err() { echo "(!) lightpanda: $*" >&2; exit 1; }

ensure_deps() {
    if command -v curl >/dev/null 2>&1 && [ -e /etc/ssl/certs/ca-certificates.crt ]; then
        return
    fi
    command -v apt-get >/dev/null 2>&1 || err "curl and ca-certificates are required and apt-get is not available"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y --no-install-recommends curl ca-certificates
    rm -rf /var/lib/apt/lists/*
}

detect_arch() {
    case "$(uname -m)" in
        x86_64 | amd64) echo "x86_64" ;;
        aarch64 | arm64) echo "aarch64" ;;
        *) err "unsupported architecture: $(uname -m)" ;;
    esac
}

# The upstream aarch64 binary needs glibc >= 2.38. Fail early with a clear
# message; if the version can't be determined, continue.
check_glibc() {
    local out ver major minor
    out="$(getconf GNU_LIBC_VERSION 2>/dev/null || true)"
    ver="$(printf '%s' "${out}" | sed -n 's/^glibc \([0-9][0-9]*\.[0-9][0-9]*\).*/\1/p')"
    if [ -z "${ver}" ] && command -v ldd >/dev/null 2>&1; then
        ver="$(ldd --version 2>&1 | head -n 1 | grep -Eo '[0-9]+\.[0-9]+$' || true)"
    fi
    [ -n "${ver}" ] || return 0
    major="${ver%%.*}"
    minor="${ver#*.}"
    if [ "${major}" -lt 2 ] || { [ "${major}" -eq 2 ] && [ "${minor}" -lt 38 ]; }; then
        err "aarch64 needs glibc >= 2.38 (found ${ver}); use e.g. debian:trixie or ubuntu:24.04"
    fi
}

# Upstream tags mix 'v0.2.x' and '1.0.x' styles: try the tag as given, then
# with the leading 'v' toggled.
download() {
    local asset="$1" dest="$2" tag
    if [ "${VERSION}" = "latest" ]; then
        curl -fsSL -o "${dest}" "${REPO_URL}/releases/latest/download/${asset}" && return
        err "download of latest ${asset} failed"
    fi
    for tag in "${VERSION}" "$(toggle_v "${VERSION}")"; do
        if curl -fsL -o "${dest}" "${REPO_URL}/releases/download/${tag}/${asset}"; then
            return
        fi
    done
    err "no release asset ${asset} found for version '${VERSION}'"
}

# Verifies the downloaded binary against checksums.txt when the version is
# listed there. latest, nightly and unlisted versions are not verified.
verify() {
    local file="$1" asset="$2" expected
    expected="$(awk -v key="${VERSION#v}/${asset}" '$2 == key { print $1 }' "${CHECKSUMS}")"
    if [ -z "${expected}" ]; then
        echo "(!) lightpanda: no pinned checksum for version '${VERSION}', skipping checksum verification" >&2
        return
    fi
    echo "${expected}  ${file}" | sha256sum -c --strict --quiet - || err "checksum mismatch for ${asset} ${VERSION#v}"
    echo "lightpanda: verified sha256 of ${asset} ${VERSION#v}"
}

toggle_v() {
    case "$1" in
        v*) echo "${1#v}" ;;
        *) echo "v$1" ;;
    esac
}

# Single-quote a value for safe embedding in the generated script.
shell_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

write_wrapper() {
    {
        echo '#!/bin/sh'
        echo '# Generated by the lightpanda devcontainer feature.'
        echo "LIGHTPANDA_BIN=\"\${LIGHTPANDA_REAL_BIN:-${BIN}}\""
        if [ "${TELEMETRY}" != "true" ]; then
            echo 'export LIGHTPANDA_DISABLE_TELEMETRY=true'
        fi
        echo "USER_AGENT=$(shell_quote "${USER_AGENT}")"
        cat <<'EOF'
if [ -n "$USER_AGENT" ]; then
    case "$1" in
        serve | fetch | mcp | agent | run)
            for arg in "$@"; do
                case "$arg" in
                    --user-agent | --user-agent=* | --user-agent-suffix | --user-agent-suffix=* | \
                        --user_agent | --user_agent=* | --user_agent_suffix | --user_agent_suffix=*)
                        exec "$LIGHTPANDA_BIN" "$@" ;;
                esac
            done
            cmd="$1"
            shift
            exec "$LIGHTPANDA_BIN" "$cmd" --user-agent "$USER_AGENT" "$@"
            ;;
    esac
fi
exec "$LIGHTPANDA_BIN" "$@"
EOF
    } > "${WRAPPER}"
    chmod 755 "${WRAPPER}"
}

if [ "$(id -u)" -ne 0 ]; then
    err "the install script must be run as root"
fi

case "${USER_AGENT}" in
    *Mozilla*) err "userAgent must not contain 'Mozilla' (rejected by Lightpanda)" ;;
esac

arch="$(detect_arch)"
if [ "${arch}" = "aarch64" ]; then
    check_glibc
fi
ensure_deps
mkdir -p "${LIB_DIR}"
tmp="$(mktemp)"
download "lightpanda-${arch}-linux" "${tmp}"
verify "${tmp}" "lightpanda-${arch}-linux"
install -m 755 "${tmp}" "${BIN}"
rm -f "${tmp}"
write_wrapper

echo "lightpanda $(LIGHTPANDA_DISABLE_TELEMETRY=true "${BIN}" version) installed"
