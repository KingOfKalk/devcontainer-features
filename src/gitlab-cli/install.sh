#!/usr/bin/env bash
# Installs the GitLab CLI, glab (https://gitlab.com/gitlab-org/cli).
# The real binary goes to /usr/local/lib/gitlab-cli, a wrapper on PATH applies
# the telemetry option to every invocation. The download is verified against
# the checksums.txt published with the release.
set -euo pipefail

VERSION="${VERSION:-latest}"
TELEMETRY="${TELEMETRY:-false}"

RELEASES_URL="https://gitlab.com/gitlab-org/cli/-/releases"
LIB_DIR="/usr/local/lib/gitlab-cli"
BIN="${LIB_DIR}/glab"
WRAPPER="/usr/local/bin/glab"

err() { echo "(!) gitlab-cli: $*" >&2; exit 1; }

ensure_deps() {
    if command -v curl >/dev/null 2>&1 && [ -e /etc/ssl/certs/ca-certificates.crt ]; then
        return
    fi
    command -v apt-get >/dev/null 2>&1 || err "curl and ca-certificates are required and apt-get is not available"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y --no-install-recommends curl ca-certificates
    rm -rf /var/lib/apt/lists/*
}

detect_arch() {
    case "$(uname -m)" in
        x86_64 | amd64) echo "amd64" ;;
        aarch64 | arm64) echo "arm64" ;;
        *) err "unsupported architecture: $(uname -m)" ;;
    esac
}

# Resolves "latest" to a version (without 'v') through the release page
# permalink, which redirects to the tagged release (.../releases/v1.2.3).
resolve_latest() {
    local url tag
    url="$(curl -fsSIL -o /dev/null -w '%{url_effective}' "${RELEASES_URL}/permalink/latest")" \
        || err "could not resolve the latest release"
    tag="${url##*/}"
    case "${tag}" in
        v[0-9]*) echo "${tag#v}" ;;
        *) err "could not determine the latest release from ${url}" ;;
    esac
}

# Verifies the tarball against the release's checksums.txt (lines of
# '<sha256>  <asset>').
verify() {
    local file="$1" asset="$2" sums="$3" expected
    expected="$(awk -v key="${asset}" '$2 == key { print $1 }' "${sums}")"
    [ -n "${expected}" ] || err "no checksum for ${asset} in checksums.txt"
    echo "${expected}  ${file}" | sha256sum -c --strict --quiet - || err "checksum mismatch for ${asset}"
    echo "gitlab-cli: verified sha256 of ${asset}"
}

write_wrapper() {
    {
        echo '#!/bin/sh'
        echo '# Generated by the gitlab-cli devcontainer feature.'
        echo "GLAB_BIN=\"\${GLAB_REAL_BIN:-${BIN}}\""
        # With telemetry allowed the wrapper leaves the variable alone, so
        # glab's own default and the user's config still apply.
        if [ "${TELEMETRY}" != "true" ]; then
            echo ': "${GLAB_SEND_TELEMETRY:=false}"'
            echo 'export GLAB_SEND_TELEMETRY'
        fi
        echo 'exec "$GLAB_BIN" "$@"'
    } > "${WRAPPER}"
    chmod 755 "${WRAPPER}"
}

if [ "$(id -u)" -ne 0 ]; then
    err "the install script must be run as root"
fi

arch="$(detect_arch)"
ensure_deps

if [ "${VERSION}" = "latest" ]; then
    version="$(resolve_latest)"
else
    version="${VERSION#v}"
fi
case "${version}" in
    "" | [!0-9]* | *[!0-9A-Za-z.+-]*) err "invalid version '${VERSION}'" ;;
esac

asset="glab_${version}_linux_${arch}.tar.gz"
base="${RELEASES_URL}/v${version}/downloads"
tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

curl -fsSL -o "${tmp}/checksums.txt" "${base}/checksums.txt" \
    || err "no release found for version '${VERSION}'"
curl -fsSL -o "${tmp}/${asset}" "${base}/${asset}" \
    || err "download of ${asset} failed"
verify "${tmp}/${asset}" "${asset}" "${tmp}/checksums.txt"

tar -xzf "${tmp}/${asset}" -C "${tmp}" bin/glab || err "bin/glab not found in ${asset}"
mkdir -p "${LIB_DIR}"
install -m 755 "${tmp}/bin/glab" "${BIN}"
write_wrapper

echo "gitlab-cli: glab $(GLAB_SEND_TELEMETRY=false "${BIN}" --version | head -n 1) installed"
